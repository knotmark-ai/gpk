#!/usr/bin/env node

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = fs.realpathSync(path.resolve(path.dirname(fileURLToPath(import.meta.url)), ".."));
const sourcePluginRoot = path.join(repoRoot, "plugin");
const defaultRoot = path.join(repoRoot, "adapters", "codex");
const marker = ".generated-from-gpk";
const markerPrefix = "Generated by scripts/build-platform-adapters.mjs from plugin/ at version ";
const args = process.argv.slice(2);
if (args.length !== 0 && (args.length !== 2 || args[0] !== "--output" || args[1].startsWith("--"))) {
  throw new Error("Usage: build-platform-adapters.mjs [--output PATH]");
}
const codexRoot = path.resolve(args[1] ?? defaultRoot);

function within(parent, child) {
  const relative = path.relative(parent, child);
  return relative === "" || (!relative.startsWith(`..${path.sep}`) && relative !== ".." && !path.isAbsolute(relative));
}

// Resolve existing ancestors so a symlink cannot redirect writes into source.
function assertNoSymlinkAncestors(target) {
  let current = target;
  while (true) {
    try {
      if (fs.lstatSync(current).isSymbolicLink()) throw new Error(`Refusing symlink output path: ${current}`);
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    const parent = path.dirname(current);
    if (parent === current) break;
    current = parent;
  }
}

function walkFiles(root) {
  const files = [];
  for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
    const fullPath = path.join(root, entry.name);
    if (entry.isSymbolicLink()) throw new Error(`Refusing symlink in package: ${fullPath}`);
    if (entry.isDirectory()) files.push(...walkFiles(fullPath));
    else if (entry.isFile()) files.push(fullPath);
    else throw new Error(`Unsupported package entry: ${fullPath}`);
  }
  return files;
}

assertNoSymlinkAncestors(codexRoot);
if (within(codexRoot, repoRoot) ||
    (within(repoRoot, codexRoot) && codexRoot !== defaultRoot) ||
    codexRoot === fs.realpathSync(os.homedir()) ||
    codexRoot === fs.realpathSync(os.tmpdir())) {
  throw new Error(`Refusing unsafe output path: ${codexRoot}`);
}

// Assemble everything before changing the output. Generated files can be
// refreshed, but this builder never recursively deletes a supplied directory.
const files = new Map();
const packageJson = JSON.parse(fs.readFileSync(path.join(repoRoot, "package.json"), "utf8"));
const claudeManifest = JSON.parse(fs.readFileSync(path.join(sourcePluginRoot, ".claude-plugin", "plugin.json"), "utf8"));
if (claudeManifest.version !== packageJson.version || claudeManifest.name !== packageJson.name) {
  throw new Error("Canonical plugin identity/version differs from package.json");
}
const skillNames = fs.readdirSync(path.join(sourcePluginRoot, "skills"), { withFileTypes: true })
  .filter(entry => entry.isDirectory() && fs.existsSync(path.join(sourcePluginRoot, "skills", entry.name, "SKILL.md")))
  .map(entry => entry.name).sort();
if (!skillNames.length) throw new Error("No canonical skills found");

function mapTree(source, target, resources) {
  for (const file of walkFiles(source)) {
    if (file.endsWith(".stub") || path.basename(file) === ".gitkeep") continue;
    resources.set(file, path.join(target, path.relative(source, file)));
  }
}

// Resolve canonical file identities before rebasing links. A packaged Skill may
// reference only files vendored with that Skill, never the checkout or a stub.
function rebaseMarkdown(text, sourceFile, targetFile, resources) {
  return text.replace(/\[[^\]]*\]\(([^)]+)\)/g, (link, rawTarget) => {
    const raw = rawTarget.trim();
    const destination = raw.startsWith("<")
      ? raw.slice(1, raw.indexOf(">"))
      : raw.replace(/\s+["'][\s\S]*$/, "");
    if (!destination || destination.startsWith("#") ||
        /^[a-z][a-z0-9+.-]*:/i.test(destination)) return link;

    const targetPath = destination.split(/[?#]/, 1)[0];
    const decodedPath = decodeURIComponent(targetPath);
    if (path.isAbsolute(decodedPath)) {
      throw new Error(`Absolute local reference in ${sourceFile}: ${destination}`);
    }
    const canonicalTarget = path.resolve(path.dirname(sourceFile), decodedPath);
    const packagedTarget = resources.get(canonicalTarget);
    if (!packagedTarget) {
      throw new Error(`Unpackaged local reference in ${sourceFile}: ${destination}`);
    }
    const relative = path.relative(path.dirname(targetFile), packagedTarget)
      .split(path.sep).map(segment => encodeURIComponent(segment)).join("/");
    const rebased = relative + destination.slice(targetPath.length);
    // Retain the label, optional title and angle-bracket form verbatim.
    const replacement = rawTarget.replace(destination, rebased);
    return link.slice(0, link.length - rawTarget.length - 1) + replacement + ")";
  });
}

for (const skillName of skillNames) {
  const skillRoot = path.join("skills", skillName);
  const resources = new Map();
  mapTree(path.join(sourcePluginRoot, "skills", skillName), skillRoot, resources);
  for (const tree of ["knowledge", "runtime", "assets"]) {
    mapTree(path.join(sourcePluginRoot, tree), path.join(skillRoot, "references", "gpk", tree), resources);
  }
  for (const [source, target] of resources) {
    const content = fs.readFileSync(source);
    files.set(target, source.endsWith(".md")
      ? rebaseMarkdown(content.toString("utf8"), source, target, resources)
      : content);
  }
  files.set(path.join(skillRoot, "agents", "openai.yaml"), [
    "interface:",
    '  display_name: "GPK"',
    '  short_description: "GPK methodology and read-only assessment"',
    `  default_prompt: "Use $${skillName} to explain the GPK method and assess these notes without changing them."`,
    "policy:",
    "  allow_implicit_invocation: true",
    "",
  ].join("\n"));
}

const { name, version, description, author, homepage, repository, license, keywords } = claudeManifest;
files.set(path.join(".codex-plugin", "plugin.json"), JSON.stringify({
  name, version, description, author, homepage, repository, license, keywords,
  skills: "./skills/",
  interface: {
    displayName: "GPK",
    shortDescription: "GPK methodology and read-only assessment",
    longDescription: "A portable goal- and project-driven knowledge method. This foundation explains GPK and assesses notes; knowledge-backend write workflows are not yet implemented.",
    developerName: author.name,
    category: "Productivity",
    capabilities: ["skills"],
    websiteURL: homepage,
    brandColor: "#4F6F52",
    defaultPrompt: ["Explain the GPK method.", "Assess these notes using GPK without changing them."],
  },
}, null, 2) + "\n");
const licenseText = fs.readFileSync(path.join(repoRoot, "LICENSE"));
if (!licenseText.equals(fs.readFileSync(path.join(sourcePluginRoot, "LICENSE")))) {
  throw new Error("plugin/LICENSE must match the repository LICENSE");
}
files.set("LICENSE", licenseText);
files.set(marker, `${markerPrefix}${packageJson.version}.\n`);

if (fs.existsSync(codexRoot)) {
  if (!fs.lstatSync(codexRoot).isDirectory()) throw new Error("Output must be a directory");
  const existing = walkFiles(codexRoot);
  if (fs.readdirSync(codexRoot).length > 0) {
    const markerPath = path.join(codexRoot, marker);
    if (!fs.existsSync(markerPath) || !fs.readFileSync(markerPath, "utf8").startsWith(markerPrefix)) {
      throw new Error("Refusing nonempty output without a GPK generated marker");
    }
  }
  const unexpected = existing.map(file => path.relative(codexRoot, file)).filter(file => !files.has(file));
  if (unexpected.length) {
    throw new Error(`Refusing to remove unexpected output files: ${unexpected.join(", ")}. Review them before rebuilding.`);
  }
}

for (const [relative, content] of files) {
  const file = path.join(codexRoot, relative);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}
console.log(`Built Codex adapter with ${skillNames.length} skill(s) at ${codexRoot}`);
